// Package memory contains the small, opt-in memory data contract for the
// character Demo. It deliberately does not depend on a vector database.
package memory

import (
	"context"
	"time"
)

// Scope prevents sharing memories across operators or characters. The Demo
// operator identity is not a substitute for a child's future device identity.
type Scope struct {
	OwnerID     int64
	CharacterID int64
}

// Fact is a concise, non-sensitive preference explicitly stated in dialogue.
type Fact struct {
	Key       string    `json:"key"`
	Value     string    `json:"value"`
	UpdatedAt time.Time `json:"updated_at"`
}

// Exchange is one completed turn. A session is generated by the client and
// must be validated before this is passed to the store.
type Exchange struct {
	Scope     Scope
	SessionID string
	User      string
	Assistant string
}

// Store persists exchanges and read-optimized preference facts.
type Store interface {
	ListFacts(context.Context, Scope, int) ([]Fact, error)
	SaveExchange(context.Context, Exchange) error
	UpsertFacts(context.Context, Scope, []Fact) error
}
